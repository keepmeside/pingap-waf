import { test, expect } from "@playwright/test";
test("rate profile UI attaches, enforces 429 and unbinds without affecting control", async ({ page }) => {
  test.setTimeout(180000);
  const password=process.env.PINGAP_E2E_PASSWORD;
  if(!password) throw new Error("Isolated canary password required");
  await expect.poll(async()=>{try{return (await page.request.get("/api/health")).status()}catch{return 0}},{timeout:30000}).toBe(200);
  await page.goto("/#/login");await page.locator("#account").fill("canary-admin");await page.locator("#password").fill(password);await page.locator("#password").press("Enter");
  await expect.poll(()=>page.evaluate(()=>localStorage.getItem("pingap:loginToken"))).toBeTruthy();
  const token=await page.evaluate(()=>localStorage.getItem("pingap:loginToken"));const headers={Authorization:`Bearer ${token}`};
  const put=async(path:string,data:unknown)=>{const response=await page.request.put(`/api${path}`,{headers,data});expect(response.status(),path).toBe(200);expect((await response.json()).status).toBe("applied")};
  await put("/upstreams/app",{backends:[{addr:"fixture:8081",weight:null}],lb_algorithm:null,health_check:null,discovery:null,tls_sni:null,verify_cert:null});
  await put("/listeners/http",{addr:"0.0.0.0:8080",http2:null,tls:null,access_log:null,server_timing:null});
  await put("/domains/site",{hostnames:["site.test"],listener:"http",upstream:"app",grpc_web:false,policies:[]});
  await put("/domains/control",{hostnames:["control.test"],listener:"http",upstream:"app",grpc_web:false,policies:[]});
  await page.goto("/#/bot-manager");
  await page.getByRole("button",{name:"New rate limit profile"}).click();
  await page.getByLabel("Profile name",{exact:true}).fill("browser-rate");
  await page.getByLabel("Limit type",{exact:true}).selectOption("inflight");
  await page.getByLabel("Request ceiling",{exact:true}).fill("2.5");
  await expect(page.getByText("Concurrent ceiling: 0 active requests.",{exact:true})).toBeVisible();
  await page.getByLabel("Limit type",{exact:true}).selectOption("rate");
  await page.getByLabel("Request ceiling",{exact:true}).fill("2");
  await page.getByLabel("Counting window",{exact:true}).fill("1s");
  await page.getByLabel("Current window weight (%)",{exact:true}).fill("100");
  const saved=page.waitForResponse(r=>r.url().includes("/api/policies/limit%3Abrowser-rate")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Save policy",exact:true}).click();expect((await saved).status()).toBe(200);
  await page.reload();await expect(page.getByText("limit:browser-rate",{exact:true})).toBeVisible();
  const traffic=async(host:string)=>(await page.request.get("http://candidate:8080/",{headers:{Host:host}})).status();
  expect(await traffic("site.test")).toBe(200);
  await page.goto("/#/domains");
  const row=page.getByRole("row").filter({has:page.getByRole("cell",{name:"site",exact:true})});
  await row.getByRole("button").first().click();
  await page.getByRole("combobox").last().click();await page.getByRole("option",{name:"limit:browser-rate",exact:true}).click();
  await page.getByRole("button",{name:"Bind",exact:true}).click();
  const bound=page.waitForResponse(r=>r.url().includes("/api/domains/site")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Save domain",exact:true}).click();expect((await bound).status()).toBe(200);
  const statuses:number[]=[];
  for(let i=0;i<200&&!statuses.includes(429);i++){statuses.push(await traffic("site.test"));await page.waitForTimeout(20)}
  expect(statuses).toContain(200);expect(statuses).toContain(429);expect(await traffic("control.test")).toBe(200);
  await page.reload();await row.getByRole("button").first().click();
  await expect(page.getByText("limit:browser-rate",{exact:true})).toBeVisible();await page.getByRole("button",{name:"Remove",exact:true}).click();
  const removed=page.waitForResponse(r=>r.url().includes("/api/domains/site")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Save domain",exact:true}).click();expect((await removed).status()).toBe(200);
  expect(await traffic("site.test")).toBe(200);expect(await traffic("control.test")).toBe(200);
  const profile=await page.request.get("/api/policies/limit%3Abrowser-rate",{headers});expect(profile.status()).toBe(200);expect((await profile.json()).max).toBe(2);
  await page.goto("/#/bot-manager");
  await page.getByRole("button",{name:"New challenge profile",exact:true}).click();
  await page.getByLabel("Profile name",{exact:true}).fill("browser-challenge");
  await page.getByLabel("Provisioned key filename",{exact:true}).fill("challenge-v1");
  const createdChallenge=page.waitForResponse(r=>r.url().includes("/api/policies/challenge%3Abrowser-challenge")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Save policy",exact:true}).click();
  const created=await createdChallenge;expect(created.status()).toBe(200);
  expect(created.request().postDataJSON().config.secret_file).toBe("challenge-v1");
  expect(created.request().postDataJSON().config).not.toHaveProperty("secret");
  await page.reload();
  await page.getByRole("group",{name:"challenge:browser-challenge",exact:true}).getByRole("button",{name:"Edit",exact:true}).click();
  await expect(page.getByLabel("Provisioned key filename",{exact:true})).toHaveValue("challenge-v1");
  await page.getByLabel("Work difficulty (1–10)",{exact:true}).fill("3");
  const editedChallenge=page.waitForResponse(r=>r.url().includes("/api/policies/challenge%3Abrowser-challenge")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Save policy",exact:true}).click();
  const edited=await editedChallenge;expect(edited.status()).toBe(200);
  expect(edited.request().postDataJSON().config).not.toHaveProperty("secret_file");
  expect(edited.request().postDataJSON().config).not.toHaveProperty("secret_source");
  const inspected=await page.request.get("/api/policies/challenge%3Abrowser-challenge",{headers});expect(inspected.status()).toBe(200);
  const inspectedData=await inspected.json();expect(inspectedData.secret_file).toBe("challenge-v1");expect(inspectedData.secret_configured).toBe(true);expect(inspectedData.difficulty).toBe(3);expect(inspectedData).not.toHaveProperty("secret");

});
